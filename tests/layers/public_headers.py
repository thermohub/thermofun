"""The installed headers are the public ones and what they include (review of v2, Q6, decision 8).

PUBLIC lists the headers of the API. ThermoFun/PublicHeaders.cmake lists what is installed: the headers that the public
ones include, directly or not. This script checks the two agree, and with --write makes the CMake list again.
    python3 tests/layers/public_headers.py [--write]
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "ThermoFun")
CMAKE = os.path.join(ROOT, "PublicHeaders.cmake")
PUBLIC = [
    "ThermoFun.h", "ThermoEngine.h", "Database.h", "Substance.h", "Reaction.h", "Element.h",
    "Batch/ThermoBatch.h", "Batch/Tables.h", "Common/Diagnostics.h", "Methods/MethodCatalog.h", "Methods/Evaluate.h",
]
INCLUDE = re.compile(r'#\s*include\s*[<"]([^>"]+)[>"]')


def public():
    roots = list(PUBLIC)
    roots += sorted("Model/" + f for f in os.listdir(os.path.join(ROOT, "Model")) if f.endswith(".h"))
    return roots


def resolve(name, here):
    for candidate in (os.path.join(os.path.dirname(here), name), name, name.replace("ThermoFun/", "", 1)):
        candidate = os.path.normpath(candidate)
        if os.path.exists(os.path.join(ROOT, candidate)):
            return candidate
    return None


def closure():
    seen, stack = set(), public()
    while stack:
        header = stack.pop()
        if header in seen:
            continue
        seen.add(header)
        with open(os.path.join(ROOT, header), errors="ignore") as f:
            for m in INCLUDE.finditer(f.read()):
                found = resolve(m.group(1), header)
                if found and found.endswith((".h", ".hpp")):
                    stack.append(found)
    return sorted(seen)


def cmake_text(headers):
    lines = ["# Generated by tests/layers/public_headers.py --write: the public headers and what they include.",
             "# The other headers of the source tree are not installed.", "set(THERMOFUN_PUBLIC_HEADERS"]
    lines += ["    " + h for h in headers]
    lines += [")", ""]
    return "\n".join(lines)


def main():
    text = cmake_text(closure())
    if "--write" in sys.argv:
        with open(CMAKE, "w") as f:
            f.write(text)
        return 0
    current = open(CMAKE).read() if os.path.exists(CMAKE) else ""
    if current != text:
        print("ThermoFun/PublicHeaders.cmake does not list the public headers and what they include: run\n"
              "    python3 tests/layers/public_headers.py --write")
        return 1
    print("public headers: %d installed" % len(closure()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
